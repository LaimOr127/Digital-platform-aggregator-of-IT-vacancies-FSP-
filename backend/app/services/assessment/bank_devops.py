@computed("devops.capacity", 5, "Планирование ресурсов", DEVOPS, ("kubernetes",))
def capacity(rng: random.Random) -> Item:
    rps, per_pod = 50 * rng.randint(12, 240), rng.choice([100, 150, 200, 250, 300, 400])
    reserve = rng.randint(1, 3)
    pods = -(-rps // per_pod) + reserve
    return numeric(
        f"Пиковая нагрузка — {number(rps)} запросов в секунду, один под выдерживает {per_pod}. "
        f"Нужен запас на падение {reserve} подов. Какое минимальное число подов задать?",
        pods,
    )
