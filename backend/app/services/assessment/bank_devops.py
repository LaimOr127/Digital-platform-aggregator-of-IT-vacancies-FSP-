@computed("devops.error-budget", 4, "SLO и бюджет ошибок", DEVOPS, ("ci-cd",))
def error_budget(rng: random.Random) -> Item:
    slo = rng.choice(["99", "99.5", "99.8", "99.9", "99.95", "99.99"])
    days = rng.choice([7, 14, 28, 30, 90])
    budget_permyriad = round((100 - float(slo)) * 100)  # доля простоя в сотых долях процента
    minutes = days * 24 * 60 * budget_permyriad // 10_000
    return numeric(
        f"SLO доступности — {slo.replace('.', ',')}% за {days} дней. Сколько полных минут простоя "
        "допускает бюджет ошибок за этот период? Округлите вниз.",
        minutes,
    )


