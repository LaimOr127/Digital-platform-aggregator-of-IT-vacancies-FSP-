@computed("devops.rolling-update", 3, "Обновление без простоя", DEVOPS, ("kubernetes",))
def rolling_update(rng: random.Random) -> Item:
    replicas, unavailable, surge = rng.randint(4, 12), rng.randint(1, 3), rng.randint(1, 3)
    if rng.random() < 0.5:
        return numeric(
            f"Deployment: {replicas} реплик, maxUnavailable: {unavailable}, maxSurge: {surge}. "
            "Сколько подов гарантированно доступно во время обновления (минимум)?",
            replicas - unavailable,
        )
    return numeric(
        f"Deployment: {replicas} реплик, maxUnavailable: {unavailable}, maxSurge: {surge}. "
        "Какое наибольшее число подов может существовать одновременно во время обновления?",
        replicas + surge,
    )


