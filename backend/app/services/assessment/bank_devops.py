_RWX = {"r": 4, "w": 2, "x": 1}


def _octal(triple: str) -> int:
    return sum(_RWX[c] for c in triple if c != "-")


@computed("devops.chmod", 1, "Права доступа Linux", DEVOPS, ("linux",))
def chmod(rng: random.Random) -> Item:
    triples = [rng.choice(["rwx", "rw-", "r-x", "r--", "---"]) for _ in range(3)]
    mode = "".join(str(_octal(t)) for t in triples)
    return numeric(
        f"Права файла: -{''.join(triples)}. Какое восьмеричное число передать chmod, "
        "чтобы установить такие права? Ответ — три цифры.",
        int(mode),
    )


