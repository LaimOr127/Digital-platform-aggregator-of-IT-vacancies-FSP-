@computed("security.entropy", 4, "Стойкость паролей", SECURITY, INFOSEC)
def entropy(rng: random.Random) -> Item:
    alphabet, name = rng.choice(
        [
            (26, "строчных латинских букв"),
            (36, "строчных букв и цифр"),
            (62, "латинских букв обоих регистров и цифр"),
            (10, "цифр"),
        ]
    )
    length = rng.randint(6, 14)
    return numeric(
        f"Пароль из {length} случайных символов из {alphabet} {name}. Сколько бит энтропии он даёт? "
        "Округлите вниз до целого.",
        math.floor(length * math.log2(alphabet)),
    )


