@computed("mobile.density", 1, "Плотность экрана", MOBILE, PLATFORMS)
def density(rng: random.Random) -> Item:
    dp = rng.choice([16, 24, 48, 56, 64])
    factor, name = rng.choice([(1.5, "hdpi"), (2, "xhdpi"), (3, "xxhdpi"), (4, "xxxhdpi")])
    return numeric(
        f"Кнопка высотой {dp} dp на экране {name} (коэффициент плотности {factor}). "
        "Сколько физических пикселей она займёт по высоте?",
        int(dp * factor),
    )


