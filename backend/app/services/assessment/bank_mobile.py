@computed("mobile.rollout", 5, "Поэтапный релиз", MOBILE, PLATFORMS)
def rollout(rng: random.Random) -> Item:
    users, percent = rng.choice([200_000, 500_000, 1_000_000]), rng.choice([1, 5, 10, 20])
    crash_tenths = rng.choice([2, 5, 10])  # доля пострадавших в десятых долях процента
    affected = users * percent * crash_tenths // 100_000
    return numeric(
        f"У приложения {users // 1000} тыс. активных пользователей. Новую версию выкатили на "
        f"{percent}% аудитории; ошибка в ней приводит к падению у {crash_tenths / 10:g}% "
        "получивших обновление. Сколько пользователей столкнутся с падением?",
        affected,
    )
