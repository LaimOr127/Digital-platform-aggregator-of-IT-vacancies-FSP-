@computed("mobile.kotlin-null", 2, "Null-безопасность Kotlin", MOBILE, ("kotlin", "android"))
def kotlin_null(rng: random.Random) -> Item:
    word = rng.choice(["kotlin", "swift", "mobile", "app"])
    value, default = rng.choice([None, word]), rng.randint(-1, 0)
    literal = "null" if value is None else f'"{value}"'
    code = f"val s: String? = {literal}\nprintln(s?.length ?: {default})"
    answer = str(default) if value is None else str(len(word))
    wrong = ["null", str(default), str(len(word)), "NullPointerException", "0"]
    return choice(rng, "Что выведет код?", answer, wrong, code)


