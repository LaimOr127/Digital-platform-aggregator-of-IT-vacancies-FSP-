@computed("data.f1", 3, "F1-мера", DATA, ML)
def f1(rng: random.Random) -> Item:
    precision, recall = 5 * rng.randint(8, 19), 5 * rng.randint(8, 19)
    # школьное округление (0,5 — вверх), а не банковское round() Python
    value = math.floor(2 * precision * recall / (precision + recall) + 0.5)
    return numeric(
        f"Точность модели — {precision}%, полнота — {recall}%. Чему равна F1-мера в процентах? "
        "Округлите до целого.",
        value,
    )


