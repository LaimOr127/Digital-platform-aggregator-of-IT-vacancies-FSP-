@computed("data.precision-recall", 2, "Метрики классификации", DATA, ML)
def precision_recall(rng: random.Random) -> Item:
    total, percent = 20 * rng.randint(2, 15), 5 * rng.randint(8, 19)  # точное целое значение
    true_positive = total * percent // 100
    errors, value = total - true_positive, percent
    if rng.random() < 0.5:
        return numeric(
            f"Модель отметила {true_positive + errors} объектов как положительные, из них верно — "
            f"{true_positive}. Какова точность (precision), в процентах?",
            value,
        )
    return numeric(
        f"Всего положительных объектов {true_positive + errors}, модель нашла {true_positive} "
        "из них. Какова полнота (recall), в процентах?",
        value,
    )


