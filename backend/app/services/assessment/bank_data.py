@computed("data.gradient-step", 4, "Градиентный спуск", DATA, ("machine-learning", "pytorch"))
def gradient_step(rng: random.Random) -> Item:
    weight = rng.randint(2, 12)
    rate, gradient = rng.choice(
        [(0.1, rng.choice([10, 20, 30, -10])), (0.5, rng.choice([2, 4, -6]))]
    )
    updated = weight - round(rate * gradient)
    return numeric(
        f"Вес w = {weight}, скорость обучения {rate:g}, градиент функции потерь по w равен "
        f"{gradient}. Каким станет w после одного шага градиентного спуска?",
        updated,
    )


