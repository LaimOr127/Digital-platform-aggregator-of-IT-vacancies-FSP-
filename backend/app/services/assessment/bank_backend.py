_STATUSES = (
    ("ресурс успешно создан", "201"),
    ("токен отсутствует или истёк", "401"),
    ("пользователь вошёл, но прав на действие нет", "403"),
    ("запрошенный ресурс не существует", "404"),
    ("превышен лимит запросов", "429"),
    ("такой email уже зарегистрирован (конфликт)", "409"),
    ("запрос принят, обработка будет выполнена позже", "202"),
    ("тело запроса не прошло валидацию", "422"),
)


@computed("backend.http-status", 1, "Коды ответа HTTP", BACKEND, ("python", "go", "java"))
def http_status(rng: random.Random) -> Item:
    situation, code = rng.choice(_STATUSES)
    wrong = rng.sample([c for _, c in _STATUSES if c != code] + ["200", "500"], 3)
    return choice(rng, f"Какой код ответа подходит лучше всего: {situation}?", code, wrong)


