@computed("backend.kafka", 4, "Очереди сообщений", BACKEND, ("kafka",))
def kafka(rng: random.Random) -> Item:
    partitions, consumers = rng.randint(3, 8), rng.randint(2, 10)
    if rng.random() < 0.5:
        return numeric(
            f"В топике {partitions} партиций, в одной группе потребителей {consumers} экземпляров. "
            "Сколько экземпляров будут простаивать без назначенных партиций?",
            max(0, consumers - partitions),
        )
    groups, messages = rng.randint(2, 4), rng.choice([100, 500, 1000])
    return numeric(
        f"В топик записали {messages} сообщений. Их читают {groups} разные группы потребителей. "
        "Сколько всего раз сообщения будут обработаны (при обработке без сбоев)?",
        messages * groups,
    )


@computed("backend.pool-size", 4, "Соединения с БД", BACKEND, ("postgresql",))
def pool_size(rng: random.Random) -> Item:
    replicas, workers, pool = rng.randint(2, 6), rng.randint(2, 8), rng.choice([5, 10, 20])
    return numeric(
        f"Сервис запущен в {replicas} репликах, в каждой {workers} процессов, у каждого процесса "
        f"пул из {pool} соединений. Сколько соединений с базой может быть открыто одновременно?",
        replicas * workers * pool,
    )


