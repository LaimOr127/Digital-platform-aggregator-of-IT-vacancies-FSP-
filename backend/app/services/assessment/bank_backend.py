@computed("backend.ttl-cache", 3, "Кэширование", BACKEND, ("redis",))
def ttl_cache(rng: random.Random) -> Item:
    ttl = rng.choice([5, 6, 8, 10, 12, 15, 20, 24, 30, 36, 40, 45, 60, 72, 90, 120, 180, 240])
    hours = rng.randint(1, 4)
    return numeric(
        f"Ключ запрашивают каждую секунду. Значение кэшируется с TTL {ttl} с; при промахе сервис "
        f"читает базу и снова кладёт значение в кэш. Сколько запросов к базе будет за {hours} ч?",
        3600 * hours // ttl,
    )


