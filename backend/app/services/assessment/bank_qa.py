@computed("qa.boundaries", 1, "Граничные значения", QA, AUTO)
def boundaries(rng: random.Random) -> Item:
    low, high = rng.randint(1, 18), rng.randint(60, 120)
    question, answer = rng.choice(
        [
            ("Какое наибольшее значение ниже допустимого диапазона стоит проверить?", low - 1),
            ("Какое наименьшее значение выше допустимого диапазона стоит проверить?", high + 1),
            ("Сколько всего допустимых значений принимает поле?", high - low + 1),
        ]
    )
    return numeric(
        f"Поле «возраст» принимает целые числа от {low} до {high} включительно. {question}",
        answer,
    )


