@computed("qa.combinations", 2, "Комбинаторика тестов", QA, AUTO)
def combinations(rng: random.Random) -> Item:
    browsers, systems, languages = rng.randint(2, 5), rng.randint(2, 4), rng.randint(2, 6)
    return numeric(
        f"Нужно проверить форму в {browsers} браузерах, на {systems} операционных системах "
        f"и на {languages} языках интерфейса. Сколько конфигураций при полном переборе?",
        browsers * systems * languages,
    )


