@computed("qa.pairwise", 4, "Попарное тестирование", QA, AUTO)
def pairwise(rng: random.Random) -> Item:
    a, b = rng.randint(3, 8), rng.randint(3, 8)
    return numeric(
        f"У двух самых «больших» параметров {a} и {b} значений, у остальных — по 2. "
        "Какое минимальное число тестов нужно, чтобы покрыть все пары значений этих двух "
        "параметров между собой?",
        a * b,
    )


