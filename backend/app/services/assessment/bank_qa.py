@computed("qa.dre", 5, "Метрики качества", QA, AUTO)
def defect_removal(rng: random.Random) -> Item:
    before, after = rng.randint(30, 150), rng.randint(1, 40)
    return numeric(
        f"До релиза команда нашла {before} дефектов, после релиза пользователи сообщили ещё о "
        f"{after}. Какова эффективность устранения дефектов (DRE), в процентах? Округлите вниз.",
        math.floor(before * 100 / (before + after)),
    )
